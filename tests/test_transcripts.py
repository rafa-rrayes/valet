"""Reading Claude Code transcripts (valet/shared/transcripts.py): the project folder a cwd's sessions are in, a
session's title as Claude Code's SDK lists it, and its conversation for a hand-off."""
import json
import shutil
import subprocess

import pytest

from tests.claude_transcripts import Chain, simple
from valet.shared import transcripts as t

CWD = "/Users/rafa/Code/project"


@pytest.mark.parametrize("cwd, folder", [("/Users/rafa/Code/valet", "-Users-rafa-Code-valet"),
                                         ("/srv/my project/v1.2_x", "-srv-my-project-v1-2-x"),
                                         ("/home/né", "-home-n-"), ("/a/😀", "-a---")])
def test_folder_names(cwd, folder):
    assert t.folder_name(cwd) == folder


# The SDK's function, as JavaScript, for a path past 200 characters (its hash is over UTF-16 code units, 32-bit).
SDK = r"""
const hash = (e) => { let t = 0; for (let n = 0; n < e.length; n++) { t = (t << 5) - t + e.charCodeAt(n); t |= 0; } return t; };
const name = (e) => { const t = e.replace(/[^a-zA-Z0-9]/g, "-"); return t.length <= 200 ? t : t.slice(0, 200) + "-" + Math.abs(hash(e)).toString(36); };
console.log(JSON.stringify(JSON.parse(require("fs").readFileSync(0, "utf8")).map(name)));
"""


@pytest.mark.skipif(shutil.which("node") is None, reason="node isn't installed")
def test_long_folder_names_match_the_sdk():
    paths = ["/x" * 150, "/Users/rafa/" + "deep/" * 50 + "né😀", "/" + "a" * 199, "/" + "a" * 200, "/" + "é" * 300]
    out = subprocess.run(["node", "-e", SDK], input=json.dumps(paths), capture_output=True, text=True, check=True)
    assert [t.folder_name(p) for p in paths] == json.loads(out.stdout)
    assert len(t.folder_name("/x" * 150)) > t.FOLDER_MAX


def ends(c: Chain) -> tuple[list[dict], list[dict]]:
    return c.records, c.records


def test_title_order():
    c = simple(CWD, ("fix the login bug", "Done."))
    assert t.summary(*ends(c)) == {"title": "fix the login bug", "cwd": CWD}
    c.line("summary", summary="Login bug fixed", leafUuid=c.last)
    assert t.summary(*ends(c))["title"] == "Login bug fixed"
    c.line("last-prompt", lastPrompt="and the logout one")
    assert t.summary(*ends(c))["title"] == "and the logout one"
    c.line("ai-title", aiTitle="Fixing auth bugs")
    assert t.summary(*ends(c))["title"] == "Fixing auth bugs"
    c.line("custom-title", customTitle="Auth")
    c.line("ai-title", aiTitle="Later AI title")
    assert t.summary(*ends(c))["title"] == "Auth"


def test_first_prompt_is_what_the_owner_typed():
    c = Chain(CWD)
    c.user("<local-command-caveat>Caveat: generated by a command</local-command-caveat>", isMeta=True)
    c.user("<command-name>/clear</command-name>\n<command-message>clear</command-message>")
    c.user("[Request interrupted by user]")
    c.user([{"type": "tool_result", "tool_use_id": "x", "content": "out"}])
    c.user("Summary of before", isCompactSummary=True)
    assert t.summary(*ends(c))["title"] == "/clear"            # a command, when nothing else was typed
    c.user([{"type": "text", "text": "<system-reminder>x</system-reminder>"}, {"type": "text", "text": "line one\nline two"}])
    assert t.summary(*ends(c))["title"] == "line one line two"
    shell = Chain(CWD)
    shell.user("<bash-input>git status</bash-input>")
    assert t.summary(*ends(shell))["title"] == "! git status"
    long = simple(CWD, ("word " * 100, "ok"))
    title = t.summary(*ends(long))["title"]
    assert len(title) <= t.TITLE_MAX + 1 and title.endswith("word…")


def test_a_subagents_transcript_isnt_a_session():
    c = Chain(CWD)
    c.user("do the subtask", isSidechain=True)
    assert t.summary(*ends(c)) is None


def test_conversation_follows_the_current_branch():
    c = Chain(CWD)
    c.user("first question")
    first = c.assistant("first answer")
    c.user("a question rewound away")
    c.assistant("an answer rewound away")
    c.last = first["uuid"]                  # the owner went back and asked again from there
    c.user([{"type": "text", "text": "second question"}, {"type": "image", "source": {}}])
    c.assistant({"type": "thinking", "thinking": "hmm"}, "Let me look.")
    c.tool("Bash", {"command": "ls -la\n  /srv", "description": "List"})
    c.tool("Read", {"file_path": "/srv/a.py"})
    c.tool("mcp__x__y", {"n": 1})
    c.assistant("Found it.", "It's in a.py.")
    c.user("sub", isSidechain=True)
    c.records.append({"type": "assistant", "uuid": "side", "parentUuid": c.last, "isSidechain": True,
                      "message": {"content": [{"type": "text", "text": "subagent text"}]}})
    assert t.conversation(c.records) == [
        {"role": "user", "text": "first question"},
        {"role": "assistant", "text": "first answer"},
        {"role": "user", "text": "second question\n[image]"},
        {"role": "assistant", "text": "Let me look."},
        {"role": "tool", "text": "Bash: ls -la /srv"},
        {"role": "tool", "text": "Read: /srv/a.py"},
        {"role": "tool", "text": 'mcp__x__y {"n": 1}'},
        {"role": "assistant", "text": "Found it.\n\nIt's in a.py."},
    ]


def test_conversation_across_a_compaction():
    c = simple(CWD, ("old question", "old answer"))
    before = c.last
    c.records.append({"type": "system", "subtype": "compact_boundary", "uuid": "boundary", "parentUuid": None,
                      "logicalParentUuid": before})
    c.last = "boundary"
    c.user("This session continues from one that ran out of context. Summary: ...", isCompactSummary=True)
    c.user("<command-name>/compact</command-name><command-args>keep the tests</command-args>")
    c.user("<local-command-stdout>Compacted</local-command-stdout>")
    c.user("new question")
    assert [(e["role"], e["text"][:20]) for e in t.conversation(c.records)] == [
        ("user", "old question"), ("assistant", "old answer"), ("summary", "This session continu"),
        ("user", "/compact keep the te"), ("user", "new question")]


def test_records_skip_what_isnt_json():
    assert t.records([b'{"a": 1}\n', "not json", b"", b"[1]", '{"b": 2}']) == [{"a": 1}, {"b": 2}]


def test_tool_lines():
    assert t.tool_line("Grep", {"pattern": "TODO", "path": "/srv"}) == "Grep: /srv"     # path comes first
    assert t.tool_line("WebFetch", {"url": "https://x.dev", "prompt": "summary"}) == "WebFetch: https://x.dev"
    assert t.tool_line("Thing", {}) == "Thing" and t.tool_line("Thing", None) == "Thing"
    assert t.tool_line("Bash", {"command": "x" * 400}).endswith("…")
