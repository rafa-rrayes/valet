"""Directive layers (valet/shared/directives.py): which entries a definition may list, where each layer's text comes
from, and how the adapters join them."""
import pytest

from valet.shared.definition import AgentDefinition, DefinitionError, load_agent, read_files
from valet.shared.directives import (
    ENVIRONMENT_FILE, OWNER_FILE, assemble, directives_error, entry_error, layer_file, preset_of, read_layers,
)

FILES = {"owner.md": "# About Alice\nHis cat is Bartolomeu.\n", "authority/full.md": "Act.\n",
         "persona.md": "You are Scout.\n", "environment.md": "# Your environment\n\nA container.\n"}


@pytest.mark.parametrize("entry", ["owner", "persona.md", "environment", "memory", "authority/full",
                                   "authority/my-rules-2"])
def test_entries_a_definition_may_list(entry):
    assert entry_error(entry) is None


@pytest.mark.parametrize("entry", ["rules.md", "Owner", "authority/", "authority/Full", "authority/../owner",
                                   "authority/a/b", "authority/-x", "env"])
def test_entries_it_may_not(entry):
    assert entry_error(entry)


def test_the_list_as_a_whole():
    assert directives_error(["owner", "authority/full", "persona.md", "environment", "memory"]) is None
    assert directives_error([]) is None
    assert directives_error(["owner", "owner"]) == "owner is listed twice"
    assert directives_error(["authority/full", "authority/strict"]) == "one authority preset at most"


def test_layer_files():
    assert [layer_file(e) for e in ["owner", "authority/full", "persona.md", "environment", "memory"]] == [
        "owner.md", "authority/full.md", "persona.md", "environment.md", "memory.md"]
    assert preset_of("authority/full") == "full" and preset_of("owner") is None


def test_assemble_follows_the_definitions_order_and_skips_empty_layers():
    text = assemble(["owner", "authority/full", "persona.md", "environment"], FILES)
    assert text == ("# About Alice\nHis cat is Bartolomeu.\n\nAct.\n\nYou are Scout.\n\n"
                    "# Your environment\n\nA container.")
    # Another order is kept as written; a layer that isn't listed, or is empty or missing, says nothing.
    assert assemble(["environment", "persona.md"], FILES) == "# Your environment\n\nA container.\n\nYou are Scout."
    assert assemble(["owner", "persona.md", "memory"], {**FILES, "owner.md": "  \n"}) == "You are Scout."
    assert assemble(["authority/strict", "persona.md"], FILES) == "You are Scout."
    assert assemble([], FILES) == "" and assemble(["persona.md"], {}) == ""
    # Literal: braces, dollar signs and template-looking text go through untouched.
    assert assemble(["persona.md"], {"persona.md": "Hi {{name}} ${x} {who}"}) == "Hi {{name}} ${x} {who}"


def test_read_layers_and_load_agent(tmp_path):
    root = tmp_path
    (root / "agents" / "scout").mkdir(parents=True)
    (root / "agents" / "scout" / "agent.yaml").write_text(
        "name: scout\ndirectives: [owner, authority/full, persona.md, environment]\n")
    (root / "agents" / "scout" / "persona.md").write_text("You are Scout.\n")
    # Nothing shared yet: the owner profile is empty and the preset missing, neither an error here.
    d, files = load_agent(root, "scout")
    assert files == {"persona.md": "You are Scout.\n"}
    (root / OWNER_FILE).write_text("Alice.\n")
    (root / "authority").mkdir()
    (root / "authority" / "full.md").write_text("Act.\n")
    (root / "authority" / "strict.md").write_text("Careful.\n")
    d, files = load_agent(root, "scout")
    assert files == {"persona.md": "You are Scout.\n", "owner.md": "Alice.\n", "authority/full.md": "Act.\n"}
    assert ENVIRONMENT_FILE not in files            # generated by the control plane at each start
    # An agent that doesn't list them doesn't get them.
    assert read_files(root, "scout") == {"persona.md": "You are Scout.\n"}
    assert read_layers(root, ["persona.md", "memory"]) == {}


def test_definition_rejects_bad_directives():
    with pytest.raises(ValueError, match="'rules.md': one of owner"):
        AgentDefinition.model_validate({"name": "x", "directives": ["persona.md", "rules.md"]})
    assert AgentDefinition(name="x").directives == ["persona.md"]       # the default, as before
    assert issubclass(DefinitionError, ValueError)
