"""Directives: the layers an agent's instructions are assembled from (DESIGN.md, "Directives"), in the order its
definition's `directives` lists them:

  owner              owner.md at the definitions repo's root: who the owner is, written in the app
  authority/<name>   authority/<name>.md at the repo's root: standing authorization, one of a few presets
  persona.md         the agent's own persona.md
  environment        generated by the control plane at every start: what this agent has, how Valet enforces it
  memory             the agent's own memory files (agents/<name>/memory/*.md, written through valet.memory), as they
                     are at each start: generated by the control plane too (control/memory.py)

The control plane sends each layer's text to the runner in agent.start's `files`, keyed by layer_file(entry), and
the generated environment and memory as well. Each harness adapter joins them with assemble(): literal text, in the
definition's order, a blank line between layers. No templating anywhere (dsh's AGENTS.md is literal, and what the owner
writes is what the agent reads)."""
import re
from collections.abc import Iterable, Mapping
from pathlib import Path

OWNER = "owner"
PERSONA = "persona.md"          # = definition.PERSONA_FILE (that module imports this one)
ENVIRONMENT = "environment"
MEMORY = "memory"
AUTHORITY = "authority/"        # + a preset's name

OWNER_FILE = "owner.md"
AUTHORITY_DIR = "authority"
ENVIRONMENT_FILE = "environment.md"
MEMORY_FILE = "memory.md"
PRESET_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,30}$")
# Where the settings page puts a layer it switches on: DESIGN.md's order. A definition may list them in any order.
ORDER = (OWNER, AUTHORITY, PERSONA, ENVIRONMENT, MEMORY)
ENTRY_RULE = "one of owner, authority/<preset>, persona.md, environment, memory"


def preset_of(entry: str) -> str | None:
    """`authority/full` -> "full"; None for any other entry."""
    if isinstance(entry, str) and entry.startswith(AUTHORITY):
        return entry[len(AUTHORITY):]
    return None


def entry_error(entry: str) -> str | None:
    """Why `entry` can't be in `directives`, or None."""
    preset = preset_of(entry)
    if preset is not None:
        return None if PRESET_RE.match(preset) else (
            f"{entry!r}: a preset name is lowercase letters, digits and dashes, at most 31")
    if entry in (OWNER, PERSONA, ENVIRONMENT, MEMORY):
        return None
    return f"{entry!r}: {ENTRY_RULE}"


def directives_error(entries: Iterable[str]) -> str | None:
    """Why the list can't be a definition's `directives`, or None: an unknown entry, one listed twice, or more than
    one authority preset."""
    seen: set[str] = set()
    for e in entries:
        if err := entry_error(e):
            return err
        if e in seen:
            return f"{e} is listed twice"
        seen.add(e)
    presets = [e for e in seen if preset_of(e) is not None]
    if len(presets) > 1:
        return "one authority preset at most"
    return None


def layer_file(entry: str) -> str | None:
    """The `files` key that carries a layer's text (agent.start; the control plane's view of the repo):
    owner.md, authority/<name>.md, persona.md, environment.md, memory.md. None for anything else."""
    if entry == OWNER:
        return OWNER_FILE
    if entry == PERSONA:
        return PERSONA
    if entry == ENVIRONMENT:
        return ENVIRONMENT_FILE
    if entry == MEMORY:
        return MEMORY_FILE
    if preset_of(entry) is not None:
        return entry + ".md"
    return None


def preset_path(root: Path, name: str) -> Path:
    """authority/<name>.md under the definitions repo `root`. ValueError for a name that isn't a preset name."""
    if not PRESET_RE.match(name):
        raise ValueError(f"{name!r}: a preset name is lowercase letters, digits and dashes, at most 31")
    return root / AUTHORITY_DIR / f"{name}.md"


def read_layers(root: Path, directives: Iterable[str]) -> dict[str, str]:
    """The shared layers `directives` lists that exist in the definitions repo at `root`: {"owner.md": text,
    "authority/<name>.md": text}. A missing one is left out (the start refuses a missing preset; an absent owner.md
    is an empty profile)."""
    out: dict[str, str] = {}
    for entry in directives:
        if entry == OWNER:
            p = root / OWNER_FILE
        elif (preset := preset_of(entry)) is not None and PRESET_RE.match(preset):
            p = preset_path(root, preset)
        else:
            continue
        if p.is_file():
            out[layer_file(entry)] = p.read_text()
    return out


def assemble(directives: Iterable[str], files: Mapping[str, str]) -> str:
    """The agent's instructions: each listed layer's text from `files` (layer_file keys), stripped, in order, a
    blank line between them; empty and missing layers left out. "" when there's nothing to say."""
    parts = []
    for entry in directives:
        key = layer_file(entry)
        text = (files.get(key) or "").strip() if key else ""
        if text:
            parts.append(text)
    return "\n\n".join(parts)
